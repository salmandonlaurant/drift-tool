function t(key, vars) {
  const dict = I18N[LANG] || I18N.el;
  let text = dict[key];
  if (text === undefined) text = I18N.el[key];
  if (text === undefined) return key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (m, name) => (
      vars[name] === undefined || vars[name] === null ? m : String(vars[name])
    ));
  }
  return text;
}

function applyStaticI18n() {
  document.documentElement.lang = LANG;
  document.title = t('app_title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  const label = document.getElementById('langLabel');
  if (label) label.textContent = LANG === 'el' ? 'EN' : 'ΕΛ';
  const btn = document.getElementById('langBtn');
  if (btn) btn.setAttribute('title', t('lang_title'));
}
